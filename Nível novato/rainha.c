// Nível Novato - Movimentação das Peças
// Implementação de Movimentação da Rainha

#include <stdio.h>

int main(){
    //Declarando a variável
    int mover = 0; //

    //Utilizando "while" para mover 8 vezes a Rainha para Esquerda.

    while (mover <= 7) //Área da condição
    {
        printf("Esquerda\n"); //Exibição do movimento indicado
        mover++; //Área da Incrementação
    }
    


    return 0;
}